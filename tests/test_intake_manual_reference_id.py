"""Reference detection uses ordinary Sample ID or Charge ID, never a dedicated ID."""

from fastapi.testclient import TestClient

from pdi_nomad_plugin.mbe.substrate_intake.app import app


def _form(**kwargs):
    data = {
        'supplier': 'CrysTec',
        'supplier_id': 'CTC',
        'crystal_id': 'GSO',
        'charge': 'P43671',
        'material': 'GdScO3',
        'orientation': '1 1 0',
        'width_mm': 10,
        'length_mm': 10,
        'thickness_mm': 0.5,
        'count': 1,
    }
    data.update(kwargs)
    return data


def test_reference_via_charge_id_uses_regular_generated_sample_lab_id():
    with TestClient(app) as client:
        response = client.post('/api/preview', json=_form(charge='P43671_reference'))
    assert response.status_code == 200, response.text
    info = response.json()
    assert len(info['archives']) == 1
    substrate = info['archives'][0]
    assert substrate['data']['lab_id'] == 'CTC_GdScO3_110_GSO_P43671_reference'
    assert substrate['data']['number_of_substrates'] == 1
    assert info['expected_children'][0]['lab_id'] == 'CTC_GSO_P43671_reference_1'
    assert substrate['data']['charge_id'] == 'P43671_reference'
    assert (
        substrate['filename'] == 'CTC_GSO_P43671_reference.SubstrateBatch.archive.json'
    )


def test_single_reference_and_normal_batch_ids():
    with TestClient(app) as client:
        charge_multi = client.post(
            '/api/preview', json=_form(charge='GSO-reference', count=10)
        )
        normal = client.post('/api/preview', json=_form(count=2))
    assert charge_multi.status_code == 422
    assert normal.status_code == 200
    assert len(normal.json()['archives']) == 1
    assert len(normal.json()['expected_children']) == 2
    assert normal.json()['archives'][0]['data']['lab_id'] == 'CTC_GdScO3_110_GSO_P43671'


def test_typed_original_fields_keep_orientation_and_autogenerated_formula():
    with TestClient(app) as client:
        result = client.post(
            '/api/preview',
            json=_form(
                subsections={
                    'electronic_properties': {
                        'carrier_density': 1e18,
                        'electrical_resistivity': 0.01,
                    },
                    'crystal_properties': {'bravais_lattices': 'Cubic Primitive'},
                }
            ),
        )
    # The exact Bravais enum varies with the installed original upstream schema.
    # The real schema may reject that example string; any failure must be 422,
    # not a new schema silently accepting the unknown enum.
    assert result.status_code in (200, 422), result.text
    if result.status_code == 200:
        data = result.json()['archives'][0]['data']
        assert data['crystal_properties']['surface_orientation']['hkl_reciprocal'] == {
            'h_index': 1,
            'k_index': 1,
            'l_index': 0,
        }
        assert data['electronic_properties']['carrier_density'] == 1e18
        assert data['components'][0]['pure_substance']['molecular_formula'] == 'GdScO3'


def test_ui_has_no_reference_id_field_and_checks_staging_before_put():
    with TestClient(app) as client:
        html = client.get('/').text
    assert 'id="reference_id"' not in html
    assert 'id="sample_id"' not in html
    assert 'id="phys_carrier_density"' in html
    assert 'id="phys_bravais"' in html
    assert 'id="prop_components"' not in html
    assert "'/rawdir/'" in html
    assert html.index("'/rawdir/'") < html.index("params.append('file_name'")
